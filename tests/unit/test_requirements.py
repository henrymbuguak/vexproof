from __future__ import annotations

from pathlib import Path

from vexproof.domain import Package
from vexproof.ingest.requirements import read_requirements
from vexproof.pipeline import merge_requirement_pins


def _write(root: Path, files: dict[str, str]) -> Path:
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return root


def test_includes_are_followed_from_a_root_that_only_includes(tmp_path: Path) -> None:
    # allegro/ralph: requirements.txt is `-r requirements/base.txt`, which includes siblings
    repo = _write(
        tmp_path,
        {
            "requirements.txt": "-r requirements/base.txt\n",
            "requirements/base.txt": "-r hermes.txt\nDjango==1.8.19\ndj.choices==0.11.0\n",
            "requirements/hermes.txt": "--requirement=openstack.txt\nhermes==1.0  # pinned\n",
            "requirements/openstack.txt": "python-novaclient==2.0\n",
        },
    )
    read = read_requirements(repo)
    assert set(read.pins) == {
        ("django", "1.8.19"),
        ("dj-choices", "0.11.0"),
        ("hermes", "1.0"),
        ("python-novaclient", "2.0"),
    }
    assert read.files[0] == "requirements.txt"


def test_ranges_are_reported_never_guessed(tmp_path: Path) -> None:
    # wagtail/bakerydemo pins with ranges
    repo = _write(
        tmp_path,
        {
            "requirements/base.txt": "Django>=3.1,<3.2\nwagtail~=2.13\nrequests==2.*\n",
            "requirements/production.txt": "-r base.txt\ngunicorn==20.1.0\nwagtail==2.13.1\n",
        },
    )
    read = read_requirements(repo)
    assert set(read.pins) == {("gunicorn", "20.1.0"), ("wagtail", "2.13.1")}
    assert set(read.unpinned) == {"django", "requests"}  # wagtail is pinned elsewhere


def test_pip_compile_hashes_markers_and_options(tmp_path: Path) -> None:
    repo = _write(
        tmp_path,
        {
            "requirements/default.txt": (
                "# autogenerated by pip-compile\n"
                "--index-url https://pypi.org/simple\n"
                "django==3.2.4 \\\n"
                "    --hash=sha256:aa \\\n"
                "    --hash=sha256:bb\n"
                "    # via -r requirements/default.in\n"
                "pywin32==300 ; sys_platform == 'win32'\n"
                "uvloop==0.15.2 ; sys_platform == 'linux'\n"
                "-e git+https://github.com/x/y.git#egg=y\n"
                "-c constraints.txt\n"
                "./vendor/local\n"
                "pkg @ https://files.test/pkg.whl\n"
            ),
            "requirements/constraints.txt": "never==1.0\n",
        },
    )
    read = read_requirements(repo)
    # constraints.txt is read as a root under requirements/, but not through -c
    assert set(read.pins) == {("django", "3.2.4"), ("uvloop", "0.15.2"), ("never", "1.0")}


def test_cycles_and_paths_outside_the_repository_are_ignored(tmp_path: Path) -> None:
    _write(tmp_path, {"outside.txt": "secret==1.0\n"})
    repo = _write(
        tmp_path / "repo",
        {"requirements.txt": "-r requirements.txt\n-r ../outside.txt\nflask==2.0.1\n"},
    )
    read = read_requirements(repo)
    assert set(read.pins) == {("flask", "2.0.1")}


def test_pins_syft_missed_are_added_and_marked_direct(tmp_path: Path) -> None:
    repo = _write(tmp_path, {"requirements/base.txt": "Django==1.8.19\nsix==1.16.0\n"})
    syft = (Package(name="six", version="1.16.0", purl="pkg:pypi/six@1.16.0"),)
    merged = merge_requirement_pins(syft, read_requirements(repo), frozenset({"django"}))
    assert [(p.name, p.version, p.direct) for p in merged] == [
        ("django", "1.8.19", True),
        ("six", "1.16.0", False),
    ]
    assert merged[0].purl == "pkg:pypi/django@1.8.19"
